/**
 * HowTo 结构化数据生成器
 * 用于「毛衣定制流程」「打样流程」等步骤类内容
 */
export function buildHowToSchema(name: string, steps: Array<{ title: string; desc: string }>) {
  return {
    '@context': 'https://schema.org',
    '@type': 'HowTo',
    name,
    totalTime: `PT${steps.length * 3}D`,
    step: steps.map((s, i) => ({
      '@type': 'HowToStep',
      position: i + 1,
      name: s.title,
      text: s.desc,
    })),
  };
}

